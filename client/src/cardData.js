const STORAGE_KEY = 'karuta-yomifuda-overrides';

export function getYomifuda() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) return { ...defaultYomifuda, ...JSON.parse(saved) };
  } catch {}
  return { ...defaultYomifuda };
}

export function saveYomifuda(overrides) {
  const diff = {};
  for (const [k, v] of Object.entries(overrides)) {
    if (v !== defaultYomifuda[k]) diff[k] = v;
  }
  if (Object.keys(diff).length === 0) {
    localStorage.removeItem(STORAGE_KEY);
  } else {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(diff));
  }
}

